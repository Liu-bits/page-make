// POST /api/projects/explorer — 创建空白项目（项目模式：虚拟文件夹 + 在线创建/编辑 html/css/js）
// body: { name? }
// 项目初始为空（无文件、无入口、无链接）；添加文件后通过 action=publish 生成公开链接
import { requireAuth, isGuestLimited } from '../../lib/session.js';
import { kvPut, keys, nowSeconds, appendLog } from '../../lib/kv.js';
import { ok, fail } from '../../lib/responses.js';
import { STATUS, normalizeKind, isBackendKind } from '../../lib/state.js';
import { canUseBackend, tierOf } from '../../lib/tiers.js';

export async function onRequest(context) {
  const { request } = context;
  const auth = await requireAuth(context);
  if (auth.error) return auth.error;
  if (request.method !== 'POST') return fail('METHOD_NOT_ALLOWED', 405);

  let body = {};
  try {
    body = await request.json();
  } catch {
    // body 可省略
  }

  // 游客限制：不可用项目模式（引导登录），且创建的链接 10 分钟后自动失效
  if (isGuestLimited(auth.user)) {
    return fail('GUEST_NO_EXPLORER', 403);
  }

  const name =
    (typeof body?.name === 'string' && body.name.trim().slice(0, 60)) || '未命名项目';

  // 部署形态三选一；普通用户只能建纯前端
  if (body?.kind !== undefined && !['static', 'npm', 'pnpm'].includes(body.kind)) {
    return fail('INVALID_KIND', 400);
  }
  const kind = normalizeKind(body?.kind);
  if (isBackendKind(kind) && !canUseBackend(auth.user)) {
    return fail('BACKEND_REQUIRES_VIP', 403);
  }

  const projectId = crypto.randomUUID().replace(/-/g, '');
  const kv = auth.kv;

  await kvPut(kv, keys.userProject(auth.user.userId, projectId), { createdAt: nowSeconds() });

  const project = {
    id: projectId,
    userId: auth.user.userId,
    provider: 'local',
    kind,
    tier: tierOf(auth.user),
    status: STATUS.READY,
    entryPath: null,
    fileCount: 0,
    size: 0,
    errorCode: null,
    sourceType: 'explorer',
    autoGenerated: false,
    diagnostics: [],
    runtimeErrors: [],
    folders: [],
    createdAt: nowSeconds(),
    expiresAt: null,
    deploymentUrl: null,
    url: null,
    files: [],
    name,
  };
  await kvPut(kv, keys.project(projectId), project);
  await appendLog(kv, { projectId, step: 'explorer_create', result: 'ok' });

  return ok({ project });
}
