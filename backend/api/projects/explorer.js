// POST /api/projects/explorer — 创建空白项目（项目模式：虚拟文件夹 + 在线创建/编辑 html/css/js）
// body: { name? }
// 项目初始为空（无文件、无入口、无链接）；添加文件后通过 action=publish 生成公开链接
import { requireAuth } from '../../lib/session.js';
import { kvPut, kvListAll, keys, nowSeconds, appendLog } from '../../lib/kv.js';
import { ok, fail } from '../../lib/responses.js';
import { STATUS } from '../../lib/state.js';

export async function onRequest(context) {
  const { request } = context;
  const auth = await requireAuth(context);
  if (auth.error) return auth.error;
  if (request.method !== 'POST') return fail('METHOD_NOT_ALLOWED', 405);

  let body = {};
  try {
    body = await request.json();
  } catch {
    // body 可省略
  }

  // 游客（免登录兜底）最多创建 1 个网页（与粘贴/上传一致）
  if (auth.user.userId.startsWith('guest_')) {
    const existing = await kvListAll(auth.kv, keys.userProject(auth.user.userId, ''));
    if (existing.length >= 1) return fail('GUEST_LIMIT', 403);
  }

  const name =
    (typeof body?.name === 'string' && body.name.trim().slice(0, 60)) || '未命名项目';

  const projectId = crypto.randomUUID().replace(/-/g, '');
  const kv = auth.kv;

  await kvPut(kv, keys.userProject(auth.user.userId, projectId), { createdAt: nowSeconds() });

  const project = {
    id: projectId,
    userId: auth.user.userId,
    provider: 'local',
    status: STATUS.READY,
    entryPath: null,
    fileCount: 0,
    size: 0,
    errorCode: null,
    sourceType: 'explorer',
    autoGenerated: false,
    diagnostics: [],
    runtimeErrors: [],
    createdAt: nowSeconds(),
    expiresAt: null,
    deploymentUrl: null,
    url: null,
    files: [],
    name,
  };
  await kvPut(kv, keys.project(projectId), project);
  await appendLog(kv, { projectId, step: 'explorer_create', result: 'ok' });

  return ok({ project });
}
