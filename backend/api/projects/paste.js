// POST /api/projects/paste — 直接粘贴代码创建网页（不经过文件上传）
// body: { provider, html, css?, js?, name? }
// 说明：html 必填；css/js 可选，写入 style.css / script.js 并自动注入 HTML 引用；
//       HTML 片段（无 <html> 结构）自动包裹成完整文档。
import { requireAuth } from '../../lib/session.js';
import { kvPut, keys, nowSeconds, appendLog } from '../../lib/kv.js';
import { ok, fail } from '../../lib/responses.js';
import { PROVIDERS, PASTE_MAX_BYTES, STATUS } from '../../lib/state.js';
import { analyzeHtml } from '../../lib/diagnostics.js';
import { deploySite } from '../../lib/deploy/index.js';

const encoder = new TextEncoder();

function bytes(text) {
  return encoder.encode(text);
}

function escapeHtml(text) {
  return String(text)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/**
 * 组装 HTML：
 * - 有 <html> 结构 → 在 </head> 前注入 CSS 引用、</body> 前注入 JS 引用（已有引用则跳过）
 * - 无结构（片段）→ 包裹成完整文档
 */
function buildHtml(html, css, js, name) {
  const hasStructure = /<html[\s>]/i.test(html);
  const cssLink = '<link rel="stylesheet" href="style.css">';
  const jsTag = '<script src="script.js"></script>';

  if (!hasStructure) {
    const head = [
      '<meta charset="utf-8">',
      '<meta name="viewport" content="width=device-width, initial-scale=1">',
      `<title>${escapeHtml(name)}</title>`,
      css ? cssLink : '',
    ].filter(Boolean).join('\n  ');
    const bodyTail = js ? `\n  ${jsTag}` : '';
    return `<!DOCTYPE html>
<html lang="zh-CN">
<head>
  ${head}
</head>
<body>
${html}${bodyTail}
</body>
</html>`;
  }

  let out = html;
  if (css && !/style\.css/i.test(out)) {
    out = /<\/head>/i.test(out)
      ? out.replace(/<\/head>/i, `  ${cssLink}\n</head>`)
      : `${cssLink}\n${out}`;
  }
  if (js && !/script\.js/i.test(out)) {
    out = /<\/body>/i.test(out)
      ? out.replace(/<\/body>/i, `  ${jsTag}\n</body>`)
      : `${out}\n${jsTag}`;
  }
  return out;
}

export async function onRequest(context) {
  const { request } = context;
  const auth = await requireAuth(context);
  if (auth.error) return auth.error;
  if (request.method !== 'POST') return fail('METHOD_NOT_ALLOWED', 405);

  let body;
  try {
    body = await request.json();
  } catch {
    return fail('BAD_REQUEST', 400);
  }

  // 单线路部署：provider 可省略，默认 local（非法值仍拒绝）
  const provider = body?.provider || 'local';
  if (!PROVIDERS.has(provider)) return fail('INVALID_PROVIDER', 400);

  const html = typeof body?.html === 'string' ? body.html : '';
  const css = typeof body?.css === 'string' ? body.css : '';
  const js = typeof body?.js === 'string' ? body.js : '';
  const name = (typeof body?.name === 'string' && body.name.trim()) || 'untitled';

  if (!html.trim()) return fail('BAD_REQUEST', 400);

  const totalBytes = bytes(html).length + bytes(css).length + bytes(js).length;
  if (totalBytes > PASTE_MAX_BYTES) return fail('TOO_LARGE', 413);

  const projectId = crypto.randomUUID().replace(/-/g, '');
  const origin = new URL(request.url).origin;
  const kv = auth.kv;
  const started = Date.now();

  try {
    // 组装文件
    const files = new Map();
    const finalHtml = buildHtml(html, css, js, name);
    files.set('index.html', bytes(finalHtml));
    if (css.trim()) files.set('style.css', bytes(css));
    if (js.trim()) files.set('script.js', bytes(js));

    // 静态诊断（与上传流程一致）
    const diagnostics = analyzeHtml(finalHtml, files);

    // 部署
    const deploy = await deploySite({ kv, env: context.env, provider, projectId, files, entryPath: 'index.html', name });

    const manifest = [...files.entries()].map(([path, data]) => ({ path, size: data.length }));

    // 写索引后写项目记录（ready 作为提交点）
    await kvPut(kv, keys.userProject(auth.user.userId, projectId), { createdAt: nowSeconds() });

    const project = {
      id: projectId,
      userId: auth.user.userId,
      provider,
      status: STATUS.READY,
      entryPath: 'index.html',
      fileCount: files.size,
      size: manifest.reduce((a, f) => a + f.size, 0),
      errorCode: null,
      sourceType: 'paste',
      autoGenerated: !/<html[\s>]/i.test(html),
      diagnostics,
      runtimeErrors: [],
      createdAt: nowSeconds(),
      expiresAt: deploy.expiresAt,
      deploymentUrl: deploy.deploymentUrl,
      url: `${origin}/p/${projectId}`,
      files: manifest,
    };
    await kvPut(kv, keys.project(projectId), project);
    await appendLog(kv, { projectId, step: 'paste', result: 'ok', duration: Date.now() - started });

    return ok({ project });
  } catch (error) {
    await appendLog(kv, {
      projectId,
      step: 'paste',
      result: 'failed',
      errorCode: error.code || 'STORAGE_ERROR',
      duration: Date.now() - started,
    });
    return fail(error.code || 'STORAGE_ERROR', error.code === 'STORAGE_ERROR' ? 500 : 400);
  }
}
