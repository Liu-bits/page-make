// 上传完成后的处理管线：组装分片 → 解压 → 找入口 → 静态诊断 → 部署 → 写库 → 清理
// 由 api/upload/finish.js 以 waitUntil 异步执行（状态机：processing → ready/failed）
import { unzip } from './zip.js';
import { findEntry, analyzeHtml, autoPreviewHtml } from './diagnostics.js';
import { deploySite } from './deploy/index.js';
import { rewriteLocalRefs, rewriteCssRefs } from './paths.js';
import {
  keys, kvGet, kvPut, kvDel, kvListAll, readChunkWithRetry,
  nowSeconds, appendLog, pathFromSiteKey,
} from './kv.js';
import { STATUS, GUEST_LINK_TTL_SECONDS } from './state.js';

function concatBytes(chunks) {
  const total = chunks.reduce((a, c) => a + c.length, 0);
  const out = new Uint8Array(total);
  let offset = 0;
  for (const chunk of chunks) {
    out.set(chunk, offset);
    offset += chunk.length;
  }
  return out;
}

/**
 * 归一 HTML 里的本地资源引用（../a.css / /a.css / ./a.css → a.css）
 *
 * ZIP 条目名已在 lib/zip.js 归一成项目内相对路径，但 HTML 内的引用字符串
 * 若原样下发，浏览器在入口页 `/p/<id>`（无尾斜杠）下会把 `../style.css`
 * 解析成 `https://host/style.css`，直接跳出 `/p/` 前缀落到站点外 → 404 断链。
 * 存储侧与引用侧必须同步改写（粘贴建站已修，这里补齐上传链路）。
 *
 * CSS 文件内部同样要处理：ZIP 里的 style.css 常写 `url(../img/bg.png)`，
 * HTML 侧归一完全覆盖不到它，下发时照样断链（背景图/字体不显示）。
 */
function normalizeHtmlRefs(files) {
  const out = new Map();
  for (const [path, data] of files) {
    if (/\.html?$/i.test(path)) {
      const rewritten = rewriteLocalRefs(new TextDecoder().decode(data));
      out.set(path, new TextEncoder().encode(rewritten));
    } else if (/\.css$/i.test(path)) {
      const rewritten = rewriteCssRefs(new TextDecoder().decode(data));
      out.set(path, new TextEncoder().encode(rewritten));
    } else {
      out.set(path, data);
    }
  }
  return out;
}

/**
 * @param {object} args { kv, upload, projectId, origin, env }
 * upload: { uploadId, userId, provider, files: [{name, size}] }
 */
export async function processUpload(args) {
  const { kv, upload, projectId, origin, env } = args;
  const started = Date.now();
  const finish = async (status, extra) => {
    const project = {
      id: projectId,
      userId: upload.userId,
      provider: upload.provider,
      status,
      ...extra,
      createdAt: nowSeconds(),
      diagnostics: extra.diagnostics ?? [],
      runtimeErrors: extra.runtimeErrors ?? [],
      files: extra.files ?? [],
    };
    await kvPut(kv, keys.project(projectId), project);
    return project;
  };

  try {
    // 1. 组装分片（KV 最终一致性：读取重试）
    const assembled = new Map();
    for (let fi = 0; fi < upload.files.length; fi++) {
      const meta = upload.files[fi];
      const chunkCount = Math.max(1, Math.ceil(meta.size / (600 * 1024)));
      const chunks = [];
      for (let ci = 0; ci < chunkCount; ci++) {
        chunks.push(await readChunkWithRetry(kv, keys.uploadChunk(upload.uploadId, fi, ci)));
      }
      const all = concatBytes(chunks);
      if (all.length !== meta.size) {
        throw Object.assign(new Error('CHUNK_SIZE_MISMATCH'), { code: 'STORAGE_ERROR' });
      }
      assembled.set(meta.name, all);
    }

    // 2. 解压 zip（过滤 __MACOSX/.DS_Store）
    const files = new Map();
    for (const [name, bytes] of assembled) {
      if (name.toLowerCase().endsWith('.zip')) {
        for (const [path, data] of await unzip(bytes)) {
          files.set(path, data);
        }
      } else {
        files.set(name, bytes);
      }
    }
    // 归一 HTML 内的本地引用字符串，使「引用路径」与「存储路径」一致（防断链）
    const htmlNormalized = normalizeHtmlRefs(files);
    files.clear();
    for (const [path, data] of htmlNormalized) files.set(path, data);

    // 3. 找入口；没有 HTML 就自动生成预览页
    let entryPath = findEntry(files);
    const autoGenerated = !entryPath;
    if (autoGenerated) {
      entryPath = 'index.html';
      files.set(entryPath, new TextEncoder().encode(autoPreviewHtml(upload.files[0]?.name || 'preview')));
    }

    // 4. 静态诊断（PHP 入口为服务端动态内容，静态检查不适用）
    const entryBytes = files.get(entryPath);
    const diagnostics = /\.html?$/i.test(entryPath)
      ? analyzeHtml(new TextDecoder().decode(entryBytes), files)
      : [];

    // 5. 部署
    const deploy = await deploySite({
      kv,
      env,
      provider: upload.provider,
      projectId,
      files,
      entryPath,
      name: upload.files[0]?.name || 'untitled',
    });

    // 6. 写库（先写索引，最后才让 ready 状态可见，避免列表查询竞态）
    const manifest = [...files.entries()].map(([path, bytes]) => ({ path, size: bytes.length }));
    const sourceType = upload.files.some((f) => f.name.toLowerCase().endsWith('.zip'))
      ? 'zip'
      : (upload.files.length === 1 ? 'single' : 'multi');

    await kvPut(kv, keys.userProject(upload.userId, projectId), { createdAt: nowSeconds() });

    const project = await finish(STATUS.READY, {
      entryPath,
      fileCount: files.size,
      size: manifest.reduce((a, f) => a + f.size, 0),
      errorCode: null,
      sourceType,
      autoGenerated,
      diagnostics,
      url: `${origin}/p/${projectId}`,
      // 游客创建的链接 10 分钟后自动失效（登录后长期有效）
      expiresAt: upload.userId?.startsWith('guest_')
        ? nowSeconds() + GUEST_LINK_TTL_SECONDS
        : deploy.expiresAt,
      deploymentUrl: deploy.deploymentUrl,
      files: manifest,
    });

    // 7. 清理临时分片
    for (let fi = 0; fi < upload.files.length; fi++) {
      const chunkCount = Math.max(1, Math.ceil(upload.files[fi].size / (600 * 1024)));
      for (let ci = 0; ci < chunkCount; ci++) {
        await kvDel(kv, keys.uploadChunk(upload.uploadId, fi, ci));
      }
    }
    await kvDel(kv, keys.upload(upload.uploadId));

    await appendLog(kv, { projectId, step: 'upload', result: 'ok', duration: Date.now() - started });
    return project;
  } catch (error) {
    const errorCode = error.code || 'STORAGE_ERROR';
    await finish(STATUS.FAILED, { errorCode });
    await appendLog(kv, { projectId, step: 'upload', result: 'failed', errorCode, duration: Date.now() - started });
    // 失败时保留临时分片便于排查（30 分钟后由新上传覆盖 / 人工清理）
    throw error;
  }
}
