import XCTest
@testable import PageMake

/// 日期解析 + 模型解码
final class ProjectDecodingTests: XCTestCase {
    private func projectJSON(
        id: String = "abc123",
        provider: String = "cloudflare",
        status: String = "ready",
        createdAt: String = "2026-10-16T10:00:00.123Z",
        expiresAt: String? = nil,
        url: String? = "https://pagemake.example.com/p/abc123",
        extra: String = ""
    ) -> Data {
        var expiresField = ""
        if let expiresAt { expiresField = "\"expiresAt\": \"\(expiresAt)\"," }
        var urlField = ""
        if let url { urlField = "\"url\": \"\(url)\"," }
        return """
        {
          "id": "\(id)",
          "provider": "\(provider)",
          "status": "\(status)",
          \(expiresField)
          \(urlField)
          \(extra)
        }
        """.data(using: .utf8)!
    }

    func testDecodesReadyProject() throws {
        let data = projectJSON()
        let project = try JSONDecoder().decode(Project.self, from: data)
        XCTAssertEqual(project.id, "abc123")
        XCTAssertEqual(project.provider, .cloudflare)
        XCTAssertEqual(project.status, .ready)
        XCTAssertEqual(project.publicURL?.absoluteString, "https://pagemake.example.com/p/abc123")
        XCTAssertEqual(project.fileCount, 0)
        XCTAssertEqual(project.diagnostics, [])
        XCTAssertNotNil(project.createdAt)
    }

    func testDecodesExpiryDate() throws {
        let data = projectJSON(status: "expired", expiresAt: "2026-10-16T13:00:00Z")
        let project = try JSONDecoder().decode(Project.self, from: data)
        XCTAssertEqual(project.status, .expired)
        XCTAssertNotNil(project.expiresAt)
    }

    func testDecodesDiagnostics() throws {
        let data = projectJSON(extra: """
        "diagnostics": [
          { "kind": "missingFile", "detail": "找不到 style.css", "suggestion": "检查文件名", "line": 8 }
        ]
        """)
        let project = try JSONDecoder().decode(Project.self, from: data)
        XCTAssertEqual(project.diagnostics.count, 1)
        XCTAssertEqual(project.diagnostics.first?.kind, .missingFile)
        XCTAssertEqual(project.diagnostics.first?.line, 8)
    }

    func testMissingOptionalFieldsUseDefaults() throws {
        let data = projectJSON(url: nil)
        let project = try JSONDecoder().decode(Project.self, from: data)
        XCTAssertNil(project.publicURL)
        XCTAssertNil(project.expiresAt)
        XCTAssertEqual(project.sourceType, "zip")
        XCTAssertFalse(project.autoGenerated)
    }

    func testBanInfoDecoding() throws {
        let json = """
        { "level": 2, "reason": "重复侵权", "until": "2026-10-23T00:00:00Z", "permanent": false }
        """.data(using: .utf8)!
        let ban = try JSONDecoder().decode(BanInfo.self, from: json)
        XCTAssertEqual(ban.level, 2)
        XCTAssertEqual(ban.reason, "重复侵权")
        XCTAssertFalse(ban.permanent)
        XCTAssertNotNil(ban.until)
    }

    func testBanInfoWithoutUntilIsPermanent() throws {
        let json = """
        { "level": 4, "reason": "严重违规", "permanent": true }
        """.data(using: .utf8)!
        let ban = try JSONDecoder().decode(BanInfo.self, from: json)
        XCTAssertTrue(ban.permanent)
        XCTAssertNil(ban.until)
    }
}

/// 日期解析工具
final class DateParsingTests: XCTestCase {
    func testParsesFractionalSeconds() {
        XCTAssertNotNil(DateParsing.parse("2026-10-16T10:00:00.123Z"))
    }

    func testParsesWithoutFractionalSeconds() {
        XCTAssertNotNil(DateParsing.parse("2026-10-16T10:00:00Z"))
    }

    func testRoundTrip() {
        let now = Date()
        let string = DateParsing.string(now)
        let parsed = DateParsing.parse(string)
        XCTAssertNotNil(parsed)
        XCTAssertEqual(parsed!.timeIntervalSince1970, now.timeIntervalSince1970, accuracy: 0.001)
    }

    func testInvalidStringReturnsNil() {
        XCTAssertNil(DateParsing.parse("not-a-date"))
    }
}
