import Foundation

/// 托管线路：当前只有单一私有部署线路。
///
/// 早期版本曾支持 EdgeOne / Cloudflare 两条线路，后端已彻底移除（`PROVIDERS`
/// 只剩 local，服务端不再读取 provider 字段做任何分支）。这里同样只保留 local：
/// 历史项目里若存着 edgeone / cloudflare，解码时统一归一为 local——那些项目
/// 实际就是由当前这套服务提供的，界面显示别的线路名会让用户以为还能选，
/// 而选择器早已不存在，等于给了个点了没反应的假入口。
enum HostProvider: String, Codable, CaseIterable, Identifiable {
    case local

    var id: String { rawValue }

    var titleKey: String { "provider_local_name" }

    var detailKey: String { "provider_local_detail" }

    /// 历史值归一：任何非 local 的旧线路都按当前唯一线路处理。
    init(rawProvider: String?) {
        self = .local
    }
}

/// 项目状态机
enum ProjectStatus: String, Codable {
    case uploading
    case processing
    case ready
    case failed
    case expired

    var titleKey: String { "status_\(rawValue)" }
}

/// 项目文件
struct ProjectFile: Identifiable, Codable, Equatable, Hashable {
    let path: String
    let size: Int64
    let contentType: String?

    var id: String { path }

    enum CodingKeys: String, CodingKey {
        case path, size, contentType
    }

    init(path: String, size: Int64, contentType: String? = nil) {
        self.path = path
        self.size = size
        self.contentType = contentType
    }

    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        path = try c.decode(String.self, forKey: .path)
        size = try c.decodeIfPresent(Int64.self, forKey: .size) ?? 0
        contentType = try c.decodeIfPresent(String.self, forKey: .contentType)
    }
}

/// 诊断项（后台静态检查 + 前端运行时检查共用）
struct DiagnosticItem: Identifiable, Codable, Equatable, Hashable {
    let kind: DiagnosticKind
    let detail: String
    let suggestion: String
    let line: Int?

    var id: String { "\(kind.rawValue)|\(detail)|\(line ?? -1)" }

    enum CodingKeys: String, CodingKey {
        case kind, detail, suggestion, line
    }

    init(kind: DiagnosticKind, detail: String, suggestion: String = "", line: Int? = nil) {
        self.kind = kind
        self.detail = detail
        self.suggestion = suggestion
        self.line = line
    }

    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        kind = (try? c.decode(DiagnosticKind.self, forKey: .kind)) ?? .other
        detail = try c.decodeIfPresent(String.self, forKey: .detail) ?? ""
        suggestion = try c.decodeIfPresent(String.self, forKey: .suggestion) ?? ""
        line = try c.decodeIfPresent(Int.self, forKey: .line)
    }

    func encode(to encoder: Encoder) throws {
        var c = encoder.container(keyedBy: CodingKeys.self)
        try c.encode(kind, forKey: .kind)
        try c.encode(detail, forKey: .detail)
        try c.encode(suggestion, forKey: .suggestion)
        try c.encodeIfPresent(line, forKey: .line)
    }
}

enum DiagnosticKind: String, Codable {
    case missingFile
    case caseMismatch
    case chinesePath
    case noEntry
    case runtimeError
    case resourceNotFound
    case other
}

/// 项目
struct Project: Identifiable, Codable, Equatable, Hashable {
    let id: String
    let name: String
    let provider: HostProvider
    let status: ProjectStatus
    let errorCode: String?
    let entryPath: String?
    let fileCount: Int
    let size: Int64
    let sourceType: String
    let autoGenerated: Bool
    let diagnostics: [DiagnosticItem]
    let runtimeErrors: [String]
    let createdAt: Date
    let expiresAt: Date?
    let publicURL: URL?
    let files: [ProjectFile]
    /// 显式创建的空文件夹（文件路径推导出的目录也由后端合并到这里）
    let folders: [String]

    enum CodingKeys: String, CodingKey {
        case id, name, provider, status, errorCode, entryPath, fileCount, size
        case sourceType, autoGenerated, diagnostics, runtimeErrors
        case createdAt, expiresAt, publicURL, url, files, folders
    }

    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(String.self, forKey: .id)
        name = try c.decodeIfPresent(String.self, forKey: .name) ?? id
        // 历史项目的 provider 可能是 edgeone / cloudflare，统一归一为当前唯一线路
        provider = HostProvider(rawProvider: try? c.decode(String.self, forKey: .provider))
        status = (try? c.decode(ProjectStatus.self, forKey: .status)) ?? .processing
        errorCode = try c.decodeIfPresent(String.self, forKey: .errorCode)
        entryPath = try c.decodeIfPresent(String.self, forKey: .entryPath)
        fileCount = try c.decodeIfPresent(Int.self, forKey: .fileCount) ?? 0
        size = try c.decodeIfPresent(Int64.self, forKey: .size) ?? 0
        sourceType = try c.decodeIfPresent(String.self, forKey: .sourceType) ?? "zip"
        autoGenerated = try c.decodeIfPresent(Bool.self, forKey: .autoGenerated) ?? false
        diagnostics = try c.decodeIfPresent([DiagnosticItem].self, forKey: .diagnostics) ?? []
        runtimeErrors = try c.decodeIfPresent([String].self, forKey: .runtimeErrors) ?? []
        createdAt = Self.decodeDate(c, .createdAt) ?? Date()
        expiresAt = Self.decodeDate(c, .expiresAt)
        let urlString = try c.decodeIfPresent(String.self, forKey: .url)
            ?? c.decodeIfPresent(String.self, forKey: .publicURL)
        publicURL = urlString.flatMap(URL.init(string:))
        files = try c.decodeIfPresent([ProjectFile].self, forKey: .files) ?? []
        folders = try c.decodeIfPresent([String].self, forKey: .folders) ?? []
    }

    func encode(to encoder: Encoder) throws {
        var c = encoder.container(keyedBy: CodingKeys.self)
        try c.encode(id, forKey: .id)
        try c.encode(name, forKey: .name)
        try c.encode(provider, forKey: .provider)
        try c.encode(status, forKey: .status)
        try c.encodeIfPresent(errorCode, forKey: .errorCode)
        try c.encodeIfPresent(entryPath, forKey: .entryPath)
        try c.encode(fileCount, forKey: .fileCount)
        try c.encode(size, forKey: .size)
        try c.encode(sourceType, forKey: .sourceType)
        try c.encode(autoGenerated, forKey: .autoGenerated)
        try c.encode(diagnostics, forKey: .diagnostics)
        try c.encode(runtimeErrors, forKey: .runtimeErrors)
        try c.encode(DateParsing.string(createdAt), forKey: .createdAt)
        try c.encodeIfPresent(expiresAt.map(DateParsing.string), forKey: .expiresAt)
        // 后端统一使用 url 字段（publicURL 仅保留解码兼容）
        try c.encodeIfPresent(publicURL?.absoluteString, forKey: .url)
        try c.encode(files, forKey: .files)
        try c.encode(folders, forKey: .folders)
    }

    private static func decodeDate(_ c: KeyedDecodingContainer<CodingKeys>, _ key: CodingKeys) -> Date? {
        guard let string = try? c.decode(String.self, forKey: key) else { return nil }
        return DateParsing.parse(string)
    }
}
